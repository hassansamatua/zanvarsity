                                <li>Submit required documents, including proof of financial support and medical examination results</li>
                                <li>Pay the visa application fee</li>
                                <li>Upon arrival in Tanzania, register with the immigration authorities</li>
                                <li>Apply for a residence permit if staying longer than 90 days</li>
